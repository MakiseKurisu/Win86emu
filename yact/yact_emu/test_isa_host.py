#!/usr/bin/env python3
"""Build and run the yact_emu host-side ISA regression harness.

The yact_emu interpreter is normally compiled for Windows, but its instruction
core (operands.cpp, onebytecmds.cpp, twobytecmds.cpp, cmdstream.cpp) only needs
the Windows integer typedefs (BYTE/WORD/DWORD/BOOL) and __fastcall.  This
script therefore compiles those *sources exactly as they are checked in*, using
a minimal windows.h shim generated in a temporary directory, and then runs
test/isa_host_test.cpp against them.

The harness drives the real dispatch tables (OneByteCmds[] / TwoByteCmds[]) via
the real ProcessCommand(), so a passing run means the shipped interpreter
executed the instructions and produced the expected registers, flags, memory
contents and instruction lengths.

Usage:
    python3 yact/yact_emu/test_isa_host.py

Exit status:
    0  harness ran and all checks passed
    1  harness ran and at least one check failed
    3  harness could not be built or run in this environment
"""

import os
import platform
import shutil
import subprocess
import sys
import tempfile

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

SOURCES = [
    "yact/yact_emu/operands.cpp",
    "yact/yact_emu/onebytecmds.cpp",
    "yact/yact_emu/twobytecmds.cpp",
    "yact/yact_emu/cmdstream.cpp",
    "yact/yact_emu/test/isa_host_test.cpp",
]

SHIM_WINDOWS_H = """\
/* Minimal stand-in for <windows.h>, generated by test_isa_host.py.
 *
 * It provides only the declarations the yact_emu interpreter core needs, so
 * that the very same interpreter sources can be compiled and executed on a
 * non-Windows host for regression testing.  It is never part of a Windows
 * build.
 */
#ifndef YACT_HOST_SHIM_WINDOWS_H
#define YACT_HOST_SHIM_WINDOWS_H

#include <stddef.h>
#include <stdint.h>

typedef unsigned char  BYTE;
typedef unsigned short WORD;
typedef unsigned int   DWORD;
typedef int            BOOL;
typedef unsigned char  UCHAR;
typedef unsigned short USHORT;
typedef unsigned int   UINT;
typedef long           LONG;
typedef unsigned long  ULONG;
typedef void          *PVOID;
typedef void          *LPVOID;

#ifndef TRUE
#define TRUE  1
#endif
#ifndef FALSE
#define FALSE 0
#endif

#define WINAPI
#define __cdecl
#define __stdcall
#define __fastcall
#define __declspec(x)
#define WINBASEAPI
#define INLINE inline

#endif /* YACT_HOST_SHIM_WINDOWS_H */
"""

SHIM_TARGETVER_H = """\
/* Generated by test_isa_host.py - the host build needs no SDK version header. */
#pragma once
"""


def find_compiler():
    for name in ("c++", "clang++", "g++"):
        path = shutil.which(name)
        if path:
            return path
    return None


def write_shim(directory):
    shim = os.path.join(directory, "shim")
    os.makedirs(shim, exist_ok=True)
    with open(os.path.join(shim, "windows.h"), "w", encoding="utf-8") as fh:
        fh.write(SHIM_WINDOWS_H)
    with open(os.path.join(shim, "targetver.h"), "w", encoding="utf-8") as fh:
        fh.write(SHIM_TARGETVER_H)
    return shim


def main():
    compiler = find_compiler()
    if compiler is None:
        print("SKIP: no C++ compiler (c++/clang++/g++) found on PATH; "
              "the yact_emu host ISA harness was not executed.")
        return 3

    for src in SOURCES:
        if not os.path.isfile(os.path.join(REPO_ROOT, src)):
            print("ERROR: missing source %s" % src)
            return 3

    workdir = tempfile.mkdtemp(prefix="yact_emu_host_")
    shim = write_shim(workdir)
    binary = os.path.join(workdir, "isa_host_test")

    cmd = [
        compiler,
        "-std=c++17",
        "-O1",
        "-g",
        "-Wno-macro-redefined",
        "-D__fastcall=",
        "-I", shim,
        "-I", os.path.join(REPO_ROOT, "yact/inc"),
        "-I", os.path.join(REPO_ROOT, "yact/yact_emu"),
    ]
    # The harness maps guest RAM at a 32-bit address, which macOS only allows
    # once the 4 GiB __PAGEZERO segment is shrunk.
    if platform.system() == "Darwin":
        cmd += ["-Wl,-pagezero_size,0x1000"]
    cmd += [os.path.join(REPO_ROOT, s) for s in SOURCES]
    cmd += ["-o", binary]

    print("$ " + " ".join(cmd))
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.stdout.strip():
        print(proc.stdout.rstrip())
    if proc.stderr.strip():
        # Warnings are expected (32-bit pointers on a 64-bit host); only a
        # failure to produce a binary is fatal.
        print(proc.stderr.rstrip())
    if proc.returncode != 0 or not os.path.isfile(binary):
        print("SKIP: the harness did not build in this environment.")
        return 3

    run = subprocess.run([binary], capture_output=True, text=True)
    sys.stdout.write(run.stdout)
    sys.stderr.write(run.stderr)
    if run.returncode != 0:
        print("FAILED: yact_emu ISA harness reported failures (exit %d)." % run.returncode)
    return run.returncode


if __name__ == "__main__":
    sys.exit(main())
